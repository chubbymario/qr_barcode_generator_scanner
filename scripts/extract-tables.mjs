// Copies lookup tables (USPS Intelligent Mail, Channel Code, Code 16K, Code 49, Codablock F) out of BWIPP's PostScript
// source (bundled with bwip-js, MIT licence) so the scanner can invert them.
// Run: node scripts/extract-imb-tables.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const ps = readFileSync(new URL('../node_modules/bwip-js/barcode.ps', import.meta.url), 'utf8');
const table = (name) => {
  const m = new RegExp(`/onecode\\.${name} \\[([^\\]]+)\\]`).exec(ps);
  if (!m) throw new Error(`table ${name} not found`);
  return m[1].trim().split(/\s+/).map(Number);
};
const tab513 = table('tab513');
const tab213 = table('tab213');
const barmap = table('barmap');
if (tab513.length !== 1287 || tab213.length !== 78 || barmap.length !== 260)
  throw new Error('unexpected table sizes');
// Channel Code: memoised enumeration states, one list per channel count (3..8).
const memoSrc = /\/channelcode\.memo \[([\s\S]*?)\] readonly def/.exec(ps)[1];
const channelMemo = memoSrc
  .split(/%\s*CH\d/)
  .slice(1)
  .map((block) =>
    [
      ...block.matchAll(
        /\[\s*(\d+)\s*\[([\d ]+)\]\s*\[([\d ]+)\]\s*\[([\d ]+)\]\s*\[([\d ]+)\]\s*\]/g,
      ),
    ].map((m) => [Number(m[1]), ...m.slice(2, 6).map((a) => a.trim().split(/\s+/).map(Number))]),
  );
if (channelMemo.length !== 6) throw new Error('channel memo not found');

// Strings in a PostScript array like /name [ (123) (456) ... ]
const psStrings = (name) => {
  const m = new RegExp(`/${name.replace('.', '\\.')} \\[([\\s\\S]*?)\\] readonly def`).exec(ps);
  if (!m) throw new Error(`${name} not found`);
  return [...m[1].matchAll(/\(([0-9]+)\)/g)].map((x) => x[1]);
};
const code16kEncs = psStrings('code16k.encs');
const code16kStart = psStrings('code16k.startencs');
const code16kStopOdd = psStrings('code16k.stopencsodd');
const code16kStopEven = psStrings('code16k.stopencseven');
const codablockEncs = psStrings('codablockf.encs');
const c49 = psStrings('code49.patterns');
const c49parity = psStrings('code49.parity');
const combosSrc = /\/code49\.combos \[([\s\S]*?)\] readonly def/.exec(ps)[1];
const c49combos = [...combosSrc.matchAll(/\((..)\)/g)].map((x) => x[1]).join('');
if (c49combos.length !== 256) throw new Error('code49 combos not found');
// PosiCode: pattern tables per version (widths as characters, ';' = 11, '<' = 12)
// and the three character sets.
const posiEncs = {};
for (const v of ['a', 'b', 'limiteda', 'limitedb']) {
  const m = new RegExp(`/${v}\\s*\\[([\\s\\S]*?)\\]`).exec(
    /\/posicode\.encmaps <<([\s\S]*?)>> readonly def/.exec(ps)[1],
  );
  posiEncs[v] = [...m[1].matchAll(/\(([0-9;<]+)\)/g)].map((x) => x[1]);
}
const posiSrc = /\/posicode\.charmapsnormal \[([\s\S]*?)\] readonly def/.exec(ps)[1];
const tok = String.raw`(\(.\)|-?\d+|[a-z]+\d)`;
const posiSets = [
  ...posiSrc.matchAll(new RegExp(String.raw`\[\s*${tok}\s+${tok}\s+${tok}\s*\]`, 'g')),
].map((m) =>
  m
    .slice(1, 4)
    .map((t) =>
      t.startsWith('(') ? t[1] : /^\d+$/.test(t) ? String.fromCharCode(Number(t)) : `#${t}`,
    ),
);
if (posiSets.length !== 46 || posiEncs.a.length !== 48 || posiEncs.limiteda.length !== 40)
  throw new Error('posicode tables not found');
// MicroPDF417 (for GS1 CC-A): 3 clusters x 929 17-bit codeword patterns,
// row address patterns (left/right, centre), and CC-A symbol sizes.
const nestedNumbers = (name) => {
  const m = new RegExp(`/${name.replace('.', '\\.')} \\[([\\s\\S]*?)\\] readonly def`).exec(ps);
  if (!m) throw new Error(`${name} not found`);
  return m[1].split(/\]\s*\[/).map((part) =>
    part
      .replace(/%[^\n]*/g, '')
      .match(/-?\d+/g)
      .map(Number),
  );
};
const mpdfClusters = nestedNumbers('micropdf417.clusters');
const mpdfRaps = nestedNumbers('micropdf417.raps');
const ccaMetrics = nestedNumbers('micropdf417.ccametrics');
const mpdfMetrics = nestedNumbers('micropdf417.nonccametrics');
if (
  mpdfClusters.length !== 3 ||
  mpdfClusters.some((c) => c.length !== 929) ||
  mpdfRaps.length !== 2 ||
  ccaMetrics.length !== 17
)
  throw new Error('micropdf417 tables not found');
if (code16kEncs.length !== 107 || codablockEncs.length !== 105 || c49.length !== 4802)
  throw new Error('unexpected stacked table sizes');
const out = `// Generated by scripts/extract-imb-tables.mjs from BWIPP (bwip-js/barcode.ps, MIT licence).
// USPS Intelligent Mail: 5-of-13 and 2-of-13 character tables and the bar-to-character map.
export const TAB513 = ${JSON.stringify(tab513)};
export const TAB213 = ${JSON.stringify(tab213)};
/** For bar i: [descender char, descender bit, ascender char, ascender bit] at i*4. */
export const BARMAP = ${JSON.stringify(barmap)};
/** Channel Code enumeration checkpoints for 3..8 channels: [value, b1..b8, s1..s8, b1max..b7max, s1max..s7max]. */
/** Code 16K: 107 character patterns (6 widths each), row start/stop patterns. */
export const CODE16K_ENCS = ${JSON.stringify(code16kEncs.join(''))};
export const CODE16K_START = ${JSON.stringify(code16kStart)};
export const CODE16K_STOP_ODD = ${JSON.stringify(code16kStopOdd)};
export const CODE16K_STOP_EVEN = ${JSON.stringify(code16kStopEven)};
/** Codablock F: Code 128 patterns (103 start A, 104 stop has 7 widths). */
export const CODABLOCK_ENCS = ${JSON.stringify(codablockEncs)};
/** Code 49: even-parity then odd-parity patterns, 2401 each, 8 widths per pattern. */
export const CODE49_PATTERNS = ${JSON.stringify(c49.join(''))};
export const CODE49_PARITY = ${JSON.stringify(c49parity)};
/** Code 49: for ASCII 0..127, the two-character shifted encoding ("1A" = shift 1 + A, " A" = A). */
export const CODE49_COMBOS = ${JSON.stringify(c49combos)};
/** PosiCode: per version, codeword patterns then start and stop. */
export const POSICODE_ENCS: Record<string, string[]> = ${JSON.stringify(posiEncs)};
/** PosiCode character sets 0/1/2 per codeword value; "#name" marks a control (la0, sf1, fn1...). */
export const POSICODE_SETS: string[][] = ${JSON.stringify(posiSets)};
/** MicroPDF417 codeword patterns (17 bits each) for clusters 0, 3, 6. */
export const MPDF_CLUSTERS: number[][] = ${JSON.stringify(mpdfClusters)};
/** MicroPDF417 row address patterns (10 bits): [left/right, centre]. */
export const MPDF_RAPS: number[][] = ${JSON.stringify(mpdfRaps)};
/** GS1 CC-A sizes: [columns, rows, EC codewords, left RAP, centre RAP, right RAP]. */
export const CCA_METRICS: number[][] = ${JSON.stringify(ccaMetrics)};
/** MicroPDF417 sizes (used by GS1 CC-B): [columns, rows, EC codewords, left, centre, right RAP]. */
export const MPDF_METRICS: number[][] = ${JSON.stringify(mpdfMetrics)};
export const CHANNEL_MEMO: [number, number[], number[], number[], number[]][][] = ${JSON.stringify(channelMemo)};
`;
writeFileSync(new URL('../src/scan/extra/tables.ts', import.meta.url), out);
console.log('ok', tab513.length, tab213.length, barmap.length);

// Format names, so menus can list them without loading bwip-js (~1 MB).
{
  const { createRequire } = await import('node:module');
  const bwipjs = createRequire(import.meta.url)('bwip-js');
  const names = Object.fromEntries(bwipjs.symbolList.map((s) => [s.bcid, s.desc]));
  writeFileSync(
    new URL('../src/barcode/names.ts', import.meta.url),
    `// Generated by scripts/extract-tables.mjs from bwip-js's symbol list.\nexport const SYMBOL_NAMES: Record<string, string> = ${JSON.stringify(names, null, 2)};\n`,
  );
}
