const GS1_VARIANT: Record<string, string> = {
  code128: 'gs1-128',
  datamatrix: 'gs1datamatrix',
  qrcode: 'gs1qrcode',
};

export function bcidForZxing(format: string, contentType?: string): string | undefined {
  const id = ZXING_TO_BCID[format];
  if (id && contentType === 'GS1' && GS1_VARIANT[id]) return GS1_VARIANT[id];
  return id;
}

